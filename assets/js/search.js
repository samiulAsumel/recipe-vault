/* search.js -- home page filter/sort. All 30 cards already exist in the DOM;
   this only hides, reorders, and counts what's already there. */
'use strict';

document.addEventListener('DOMContentLoaded', function () {
  const grid = document.getElementById('recipe-grid');
  const searchInput = document.getElementById('recipe-search');
  const categorySelect = document.getElementById('category-select');
  const sortSelect = document.getElementById('sort-select');
  const chips = Array.from(document.querySelectorAll('.chip[data-diet]'));
  const status = document.getElementById('filter-status');
  const emptyState = document.getElementById('empty-state');
  const clearButton = document.getElementById('clear-filters');
  if (!grid || !searchInput) return;

  const cards = Array.from(grid.querySelectorAll('.card'));

  // Generated by tools/build.js; a blocked or stale script degrades to
  // matching against the card's own title instead of throwing.
  const index = typeof RECIPES_INDEX !== 'undefined' ? RECIPES_INDEX : null;
  const haystackBySlug = {};
  if (index) {
    for (const entry of index) haystackBySlug[entry.slug] = entry.haystack;
  }

  function foldDiacritics(text) {
    return text.normalize('NFD').replace(/[̀-ͯ]/g, '');
  }
  function tokenize(text) {
    return foldDiacritics(text.toLowerCase()).split(/[^a-z0-9]+/).filter(Boolean);
  }

  // setTimeout rather than requestAnimationFrame: rAF is fully suspended by
  // the browser while a tab is backgrounded, which would stall filtering
  // indefinitely on tab-switch; a short timeout still debounces keystrokes
  // but always eventually fires.
  let applyTimer = null;
  function scheduleApply() {
    if (applyTimer) clearTimeout(applyTimer);
    applyTimer = setTimeout(function () {
      applyTimer = null;
      apply();
    }, 100);
  }

  function activeDiets() {
    return chips.filter((c) => c.getAttribute('aria-pressed') === 'true').map((c) => c.dataset.diet);
  }

  function matchesText(card, tokens) {
    if (!tokens.length) return true;
    const haystack = haystackBySlug[card.dataset.slug] || card.dataset.title;
    return tokens.every((t) => haystack.includes(t));
  }

  function apply() {
    const tokens = tokenize(searchInput.value);
    const category = categorySelect.value;
    const diets = activeDiets();
    let visibleCount = 0;

    for (const card of cards) {
      const textOk = matchesText(card, tokens);
      const catOk = category === 'all' || card.dataset.category === category;
      const dietTags = card.dataset.dietary.split(' ');
      const dietOk = diets.every((d) => dietTags.includes(d));
      const visible = textOk && catOk && dietOk;
      card.hidden = !visible;
      if (visible) visibleCount += 1;
    }

    sortCards();

    if (status) status.textContent = `Showing ${visibleCount} of ${cards.length} recipes`;
    if (emptyState) emptyState.hidden = visibleCount !== 0;

    syncUrl(tokens.length ? searchInput.value : '', category, diets);
  }

  function sortCards() {
    const mode = sortSelect ? sortSelect.value : 'az';
    const sorted = cards.slice().sort((a, b) => {
      if (mode === 'quick') return Number(a.dataset.total) - Number(b.dataset.total);
      if (mode === 'new') return b.dataset.published.localeCompare(a.dataset.published);
      return a.dataset.title.localeCompare(b.dataset.title);
    });
    for (const card of sorted) grid.appendChild(card);
  }

  // Preserves whatever hash is already there rather than forcing "#all" --
  // changing a URL's fragment via replaceState to point at an existing
  // element makes Chrome scroll to it, so unconditionally adding "#all"
  // here silently auto-scrolled every fresh homepage visit straight to the
  // recipe grid, past the hero, before the visitor did anything.
  function syncUrl(q, category, diets) {
    const params = new URLSearchParams();
    if (q) params.set('q', q);
    if (category !== 'all') params.set('category', category);
    if (diets.length) params.set('diet', diets.join(','));
    const query = params.toString();
    const hash = location.hash || '';
    const url = query ? `${location.pathname}?${query}${hash}` : `${location.pathname}${hash}`;
    history.replaceState(null, '', url);
  }

  function applyFromUrl() {
    const params = new URLSearchParams(location.search);
    const q = params.get('q');
    const category = params.get('category');
    const diets = (params.get('diet') || '').split(',').filter(Boolean);
    if (q) searchInput.value = q;
    if (category && categorySelect.querySelector(`option[value="${category}"]`)) {
      categorySelect.value = category;
    }
    for (const chip of chips) {
      chip.setAttribute('aria-pressed', diets.includes(chip.dataset.diet) ? 'true' : 'false');
    }
  }

  searchInput.addEventListener('input', scheduleApply);
  categorySelect.addEventListener('change', scheduleApply);
  if (sortSelect) sortSelect.addEventListener('change', scheduleApply);
  for (const chip of chips) {
    chip.addEventListener('click', function () {
      const pressed = chip.getAttribute('aria-pressed') === 'true';
      chip.setAttribute('aria-pressed', pressed ? 'false' : 'true');
      scheduleApply();
    });
  }
  if (clearButton) {
    clearButton.addEventListener('click', function () {
      searchInput.value = '';
      categorySelect.value = 'all';
      for (const chip of chips) chip.setAttribute('aria-pressed', 'false');
      scheduleApply();
    });
  }

  applyFromUrl();
  apply();
});
